const POINTS_BY_ID = {};
const POINTS_BY_MERIDIAN = {};
POINTS.forEach((pt) => {
  /* 经内序号统一由标准代码推导（LI4 → 4），保证沿经脉顺序排列 */
  const m = /^([A-Z]+)(\d+)$/.exec(pt.id);
  pt.o = m ? +m[2] : pt.o || 0;
  POINTS_BY_ID[pt.id] = pt;
  (POINTS_BY_MERIDIAN[pt.m] = POINTS_BY_MERIDIAN[pt.m] || []).push(pt);
});
// 按经内序号排序
Object.values(POINTS_BY_MERIDIAN).forEach((arr) => arr.sort((a, b) => a.o - b.o));

