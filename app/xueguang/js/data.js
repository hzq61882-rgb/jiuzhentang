/* 自检：缺字段 / 重复代码（开发期用，控制台可见） */
function auditPoints() {
  const seen = {};
  const problems = [];
  POINTS.forEach((p) => {
    if (seen[p.id]) problems.push("重复代码：" + p.id);
    seen[p.id] = 1;
    ["n", "p", "m", "loc", "ind", "op", "tip"].forEach((k) => {
      if (!p[k]) problems.push(p.id + " 缺字段 " + k);
    });
    if (!MERIDIAN_BY_CODE[p.m]) problems.push(p.id + " 经脉代码无效 " + p.m);
  });
  return problems;
}

